export function resolverTema(
  preferencia: PreferenciaTema,
  esquemaDoSistema?: TemaResolvido | null,
): TemaResolvido {
  if (preferencia === "Claro") return "light";
  if (preferencia === "Escuro") return "dark";
  return esquemaDoSistema === "dark" ? "dark" : "light";
}
